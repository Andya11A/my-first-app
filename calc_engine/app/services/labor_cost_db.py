def list_regions() -> list[str]:
    """返回所有可用地区列表"""
    regions = set()
    regions.update(LABOR_DAILY_WAGE.keys())
    regions.update(LABOR_UNIT_PRICE.keys())
    return sorted(regions)


def list_trades() -> list[str]:
    """返回所有工种列表"""
    return list(LAB_TRADE_LABOR_COST.keys())


def get_daily_wage(region: str, trade: Optional[str] = None) -> dict:
    """查询某地区某工种的日工资信息价

    Args:
        region: 地区名（广州/深圳/北京/上海）
        trade: 工种名（可选，不传则返回全部）

    Returns:
        工资信息字典
    """
    data = LABOR_DAILY_WAGE.get(region)
    if not data:
        return {"error": f"未找到地区: {region}", "available": list_regions()}
    if trade:
        wage = data["wages"].get(trade)
        if not wage:
            return {"error": f"未找到工种: {trade}", "available": list(data["wages"].keys())}
        return {
            "region": region, "trade": trade,
            "low": wage["low"], "high": wage["high"], "unit": wage["unit"],
            "source": data["source"], "publish_date": data["publish_date"],
        }
    return {
        "region": region,
        "source": data["source"],
        "publish_date": data["publish_date"],
        "wages": data["wages"],
    }


def get_trade_labor_cost(trade: str) -> dict:
    """查询某工种的人工费数据（含所有地区）

    Args:
        trade: 工种名称

    Returns:
        工种人工费数据字典
    """
    data = LAB_TRADE_LABOR_COST.get(trade)
    if not data:
        return {"error": f"未找到工种: {trade}", "available": list(LAB_TRADE_LABOR_COST.keys())}
    return {
        "trade": trade,
        "unit": data["unit"],
        "regions": data["regions"],
        "notes": data.get("notes", ""),
    }


