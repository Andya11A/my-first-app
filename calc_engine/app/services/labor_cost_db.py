def get_labor_cost(trade: str, city: str = "广州") -> dict:
    """获取某工种人工费，按城市调整"""
    data = LABOR_COST_DB.get(trade)
    if not data:
        return {"unit": "㎡", "low": 0, "high": 0, "trade": trade, "city": city, "note": "该工种暂无人工费数据，需手动补充"}

    factor = CITY_FACTORS.get(city, CITY_FACTORS["其他"])
    low = round(data["price_range"][0] * factor, 1)
    high = round(data["price_range"][1] * factor, 1)
    return {
        "trade": trade,
        "unit": data["unit"],
        "low": low,
        "high": high,
        "city": city,
        "factor": factor,
        "source": data["source"],
        "year": data["year"],
        "note": data.get("note", ""),
    }


