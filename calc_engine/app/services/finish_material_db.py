# ================================================================
# 辅助函数
# ================================================================

def list_categories() -> list:
    """列出所有材料大类"""
    return list(MATERIAL_DB.keys())


def list_materials_in_category(category: str) -> list:
    """列出某大类下所有材料名称"""
    cat = MATERIAL_DB.get(category)
    return list(cat.keys()) if cat else []


def get_material_info(category: str, material_name: str) -> dict:
    """查询单个材料详情"""
    cat = MATERIAL_DB.get(category, {})
    return cat.get(material_name, {})


def search_by_lab_type(lab_type: str) -> dict:
    """按实验室类型搜索适用材料"""
    results = {}
    for category, materials in MATERIAL_DB.items():
        matched = {}
        for name, info in materials.items():
            if lab_type in info.get("applicable", []):
                matched[name] = info
        if matched:
            results[category] = matched
    return results


def get_all_materials_flat() -> list:
    """扁平化返回所有材料列表"""
    flat = []
    for category, materials in MATERIAL_DB.items():
        for name, info in materials.items():
            flat.append({
                "category": category,
                "name": name,
                **info,
            })
    return flat


def get_material_count() -> dict:
    """统计材料数量"""
    counts = {}
    total = 0
    for category, materials in MATERIAL_DB.items():
        count = len(materials)
        counts[category] = count
        total += count
    counts["total"] = total
    return counts
