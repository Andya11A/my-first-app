# 五、查询辅助函数
# ================================================================
def list_regions() -> list[str]:
    """返回所有可用地区列表"""
    return sorted(set(list(MANAGEMENT_FEE_RATE.keys()) + list(PROFIT_RATE.keys())))


def get_management_fee_rate(region: str, project_type: str = "装饰装修工程") -> dict:
    """查询企业管理费费率

    Args:
        region: 地区（湖南/福建/甘肃）
        project_type: 工程类型（装饰装修工程/建筑工程/安装工程等）

    Returns:
        费率字典
    """
    data = MANAGEMENT_FEE_RATE.get(region)
    if not data:
        return {"error": f"未找到地区: {region}", "available": list_regions()}
    rate_info = data["rates"].get(project_type)
    if not rate_info:
        return {"error": f"未找到工程类型: {project_type}", "available": list(data["rates"].keys())}
    return {
        "region": region,
        "project_type": project_type,
        "rate_percent": rate_info["rate"],
        "base": rate_info["base"],
        "source": data["source"],
        "publish_date": data["publish_date"],
    }


