def list_wall_categories() -> list:
    """列出所有墙体大类"""
    return list(WALL_SYSTEM_DB.keys())


def list_wall_materials_in_category(category: str) -> list:
    """列出某大类下所有材料名称"""
    cat = WALL_SYSTEM_DB.get(category)
    return list(cat.keys()) if cat else []


def get_wall_material_info(category: str, material_name: str) -> dict:
    """查询单个材料详情"""
    cat = WALL_SYSTEM_DB.get(category, {})
    return cat.get(material_name, {})


def get_jd_price_supplement(material_name: str) -> dict:
    """查询已有材料的京东比价"""
    return JD_PRICE_SUPPLEMENT.get(material_name, {})


def get_wall_material_count() -> dict:
    """统计材料数量"""
    counts = {}
    total = 0
    for category, materials in WALL_SYSTEM_DB.items():
        count = len(materials)
        counts[category] = count
        total += count
    counts["total"] = total
    counts["jd_supplement"] = len(JD_PRICE_SUPPLEMENT)
    return counts
